import type { z } from 'zod';
import type * as S from './index';

/**
 * Compiles only when A and B are assignable to each other.
 * Uses generic constraints, not a conditional type: conditional types give up on recursive
 * types such as ActorRef (onBehalfOf) and report a false mismatch.
 */
type Sub<A extends B, B> = [A, B];
type Back<B extends A, A> = Sub<B, A>;
type Out<T extends z.ZodType> = z.output<T>;

